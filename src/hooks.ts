import { cp, mkdir, readFile, rm, rmdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";

export type HookTarget = "codex" | "copilot" | "claude" | "cursor" | "antigravity";
export type HookState = "missing" | "unchanged" | "modified";

const OWNER = "dotnet-production-agent-skills";
const COMMAND = "node .agent-guardrails/guard.mjs";
const SCRIPT_DIRECTORY = ".agent-guardrails";
const SCRIPT_NAME = "guard.mjs";
const SCRIPT_NAMES = [SCRIPT_NAME, "diagnosis.mjs", "session-state.mjs", "command-policy.mjs"];
// Exact SHA-256 of the unmodified guard shipped before ownership markers.
const LEGACY_GUARD_HASHES = new Set(["5286623026e5adcf9bfd0cac0265aed0fa91186cb8294986201441b7354f685b"]);

interface JsonObject { [key: string]: unknown }

function isObject(value: unknown): value is JsonObject {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

async function readJson(file: string): Promise<JsonObject> {
  try {
    const parsed: unknown = JSON.parse(await readFile(file, "utf8"));
    if (!isObject(parsed)) throw new Error("root must be a JSON object");
    return parsed;
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return {};
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(`invalid hook configuration ${file}: ${detail}`);
  }
}

function locations(projectRoot: string, target: HookTarget): { config: string; script: string } {
  const configs: Record<HookTarget, string> = {
    codex: ".codex/hooks.json",
    copilot: ".github/hooks/dotnet-production-agent-skills.json",
    claude: ".claude/settings.json",
    cursor: ".cursor/hooks.json",
    antigravity: ".agents/hooks.json",
  };
  return { config: path.join(projectRoot, configs[target]), script: path.join(projectRoot, SCRIPT_DIRECTORY, SCRIPT_NAME) };
}

function handler(target: HookTarget): JsonObject {
  return { type: "command", command: `${COMMAND} ${target}`, timeout: 10 };
}

function managedGroup(target: HookTarget): JsonObject {
  return { matcher: target === "antigravity" ? "run_command|view_file|write_to_file|replace_file_content|multi_replace_file_content" : "Bash|PowerShell|Read|Write|Edit", hooks: [handler(target)] };
}

function containsManaged(value: unknown): boolean {
  return (JSON.stringify(value) ?? "").includes(COMMAND);
}

function withoutManaged(value: unknown): unknown[] {
  if (!Array.isArray(value)) return [];
  return value.flatMap((entry: unknown) => {
    if (!isObject(entry)) return [entry];
    if (typeof entry.command === "string" && entry.command.startsWith(`${COMMAND} `)) return [];
    if (!Array.isArray(entry.hooks)) return [entry];
    const retained = entry.hooks.filter((item: unknown) => !(isObject(item) && typeof item.command === "string" && item.command.startsWith(`${COMMAND} `)));
    return retained.length ? [{ ...entry, hooks: retained }] : containsManaged(entry) ? [] : [entry];
  });
}

function mergeConfig(current: JsonObject, target: HookTarget, install: boolean): JsonObject {
  if (target === "copilot") {
    const next = { ...current };
    const hooks = isObject(current.hooks) ? { ...current.hooks } : {};
    for (const event of ["preToolUse", "postToolUse", "postToolUseFailure"]) {
      const entries = withoutManaged(hooks[event]);
      // Migrate only the exact handler previously generated by this installer.
      // Preserve user-modified managed handlers, including their cwd/timeout.
      const original = Array.isArray(hooks[event]) ? hooks[event] as unknown[] : [];
      for (const entry of original) {
        if (!isObject(entry) || typeof entry.command !== "string" || !entry.command.startsWith(`${COMMAND} `)) continue;
        const expectedCommand = `${COMMAND} copilot${event === "preToolUse" ? "" : ` ${event}`}`;
        const owned = entry.type === "command" && entry.command === expectedCommand && entry.timeoutSec === 10
          && Object.keys(entry).every(key => ["type", "command", "timeoutSec", "cwd"].includes(key))
          && (entry.cwd === undefined || entry.cwd === ".");
        if (!owned) entries.push(entry);
      }
      if (install && !containsManaged(entries)) entries.push({ type: "command", command: `${COMMAND} copilot${event === "preToolUse" ? "" : ` ${event}`}`, cwd: ".", timeoutSec: 10 });
      if (entries.length) hooks[event] = entries; else delete hooks[event];
    }
    if (install) {
      next.version = current.version ?? 1;
      next.description = current.description ?? `${OWNER} project command guardrails`;
    } else if (current.description === `${OWNER} project command guardrails`) {
      delete next.description;
      if (Object.keys(hooks).length === 0 && current.version === 1) delete next.version;
    }
    if (Object.keys(hooks).length) next.hooks = hooks; else delete next.hooks;
    return next;
  }
  if (target === "antigravity") {
    const next = { ...current };
    const group = isObject(current[OWNER]) ? { ...current[OWNER] as JsonObject } : {};
    const existing = group.PreToolUse;
    if (install && !containsManaged(existing)) group.PreToolUse = [...(Array.isArray(existing) ? existing : []), managedGroup(target)];
    if (!install) {
      const retained = withoutManaged(existing);
      if (retained.length) group.PreToolUse = retained; else delete group.PreToolUse;
      if (group.enabled === true && Object.keys(group).length === 1) delete group.enabled;
    }
    if (Object.keys(group).length) next[OWNER] = group; else delete next[OWNER];
    return next;
  }

  const hooks = isObject(current.hooks) ? { ...current.hooks } : {};
  const event = target === "cursor" ? "preToolUse" : "PreToolUse";
  const entries = install && Array.isArray(hooks[event]) && containsManaged(hooks[event]) ? [...hooks[event] as unknown[]] : withoutManaged(hooks[event]);
  if (install && !containsManaged(entries)) entries.push(target === "cursor"
    ? { command: `${COMMAND} cursor`, timeout: 10, matcher: "Shell|Read|Write", failClosed: true }
    : managedGroup(target));
  if (entries.length) hooks[event] = entries;
  else delete hooks[event];
  const next = { ...current };
  if (target === "cursor") next.version = typeof current.version === "number" ? current.version : 1;
  if (Object.keys(hooks).length) next.hooks = hooks;
  else delete next.hooks;
  return next;
}

async function expectedScript(packageRoot: string): Promise<string> {
  return readFile(path.join(packageRoot, "hooks", SCRIPT_NAME), "utf8");
}

export async function inspectHooks(projectRoot: string, packageRoot: string, target: HookTarget): Promise<{ target: HookTarget; state: HookState; config: string; script: string }> {
  const files = locations(projectRoot, target);
  try {
    const [current, script] = await Promise.all([readJson(files.config), readFile(files.script, "utf8")]);
    const expected = mergeConfig(current, target, true);
    const configMatches = JSON.stringify(current) === JSON.stringify(expected);
    const dependenciesMatch = await Promise.all(SCRIPT_NAMES.slice(1).map(async name =>
      await readFile(path.join(projectRoot, SCRIPT_DIRECTORY, name), "utf8") === await readFile(path.join(packageRoot, "hooks", name), "utf8")));
    return { target, state: configMatches && script === await expectedScript(packageRoot) && dependenciesMatch.every(Boolean) ? "unchanged" : "modified", ...files };
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return { target, state: "missing", ...files };
    throw error;
  }
}

export async function changeHooks(projectRoot: string, packageRoot: string, target: HookTarget, action: "install" | "uninstall", dryRun: boolean): Promise<"install" | "update" | "remove" | "skip"> {
  const files = locations(projectRoot, target);
  const current = await readJson(files.config);
  const next = mergeConfig(current, target, action === "install");
  const hasConfigChange = JSON.stringify(current) !== JSON.stringify(next);
  const hash = (value: string) => createHash("sha256").update(value).digest("hex");
  const scripts = await Promise.all(SCRIPT_NAMES.map(async name => {
    const destination = path.join(projectRoot, SCRIPT_DIRECTORY, name);
    const canonical = await readFile(path.join(packageRoot, "hooks", name), "utf8");
    let content: string | null = null;
    let recorded = "";
    try { content = await readFile(destination, "utf8"); } catch (error) {
      if (!(error instanceof Error && "code" in error && error.code === "ENOENT")) throw error;
    }
    try { recorded = (await readFile(`${destination}.sha256`, "utf8")).trim(); } catch (error) {
      if (!(error instanceof Error && "code" in error && error.code === "ENOENT")) throw error;
    }
    const legacy = name === SCRIPT_NAME && content !== null && !recorded && LEGACY_GUARD_HASHES.has(hash(content));
    if (action === "install" && content !== null && content !== canonical && hash(content) !== recorded && !legacy) {
      throw new Error(`Modified or unmanaged guard script preserved: ${destination}`);
    }
    return { name, destination, canonical, matches: content === canonical };
  }));
  if (action === "install") {
    if (!hasConfigChange && scripts.every(script => script.matches)) return "skip";
    if (!dryRun) {
      await mkdir(path.dirname(files.config), { recursive: true });
      await mkdir(path.dirname(files.script), { recursive: true });
      // Install dependencies before the entrypoint that imports them.
      for (const script of [...scripts].reverse()) {
        await cp(path.join(packageRoot, "hooks", script.name), script.destination);
        await writeFile(`${script.destination}.sha256`, `${hash(script.canonical)}\n`, "utf8");
      }
      await writeFile(files.config, `${JSON.stringify(next, null, 2)}\n`, "utf8");
    }
    return Object.keys(current).length ? "update" : "install";
  }
  if (!hasConfigChange) return "skip";
  if (!dryRun) {
    if (Object.keys(next).length) await writeFile(files.config, `${JSON.stringify(next, null, 2)}\n`, "utf8");
    else await rm(files.config, { force: true });
  }
  return "remove";
}

export function hookTargets(target: string): HookTarget[] {
  if (target === "all") return ["codex", "copilot", "claude", "cursor", "antigravity"];
  return target === "shared" ? [] : [target as HookTarget];
}

export async function removeSharedHookScript(projectRoot: string, dryRun: boolean): Promise<void> {
  if (dryRun) return;
  for (const target of hookTargets("all")) {
    const config = await readJson(locations(projectRoot, target).config);
    if (containsManaged(config)) return;
  }
  const directory = path.join(projectRoot, SCRIPT_DIRECTORY);
  // Preserve the entrypoint and its dependencies if any installed file was edited.
  const removable: string[] = [];
  for (const name of SCRIPT_NAMES) {
    const script = path.join(directory, name);
    try {
      const [content, recorded] = await Promise.all([readFile(script, "utf8"), readFile(`${script}.sha256`, "utf8")]);
      if (createHash("sha256").update(content).digest("hex") !== recorded.trim()) return;
      removable.push(script);
    } catch (error) {
      if (!(error instanceof Error && "code" in error && error.code === "ENOENT")) throw error;
      // An untracked entrypoint may still import owned dependencies. Preserve
      // the complete bundle rather than breaking that retained script.
      try { await readFile(script, "utf8"); return; } catch (missing) {
        if (!(missing instanceof Error && "code" in missing && missing.code === "ENOENT")) throw missing;
      }
    }
  }
  for (const script of removable) {
    await rm(script);
    await rm(`${script}.sha256`);
  }
  try { await rmdir(directory); } catch (error) {
    if (!(error instanceof Error && "code" in error && (error.code === "ENOTEMPTY" || error.code === "ENOENT"))) throw error;
  }
}
